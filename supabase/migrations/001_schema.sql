-- ────────────────────────────────────────────────
-- 6. DIGITAL ID GENERATOR FUNCTION
-- ────────────────────────────────────────────────
-- Format: LM-IN-{state_code}-{district_code}-{year}-{seq 8 digits}
-- Example: LM-IN-HR-GGN-2026-00018452
--
-- This runs as a BEFORE INSERT trigger on instruments.
-- It atomically increments the sequence (SELECT ... FOR UPDATE)
-- which prevents duplicates even under concurrent inserts.

CREATE OR REPLACE FUNCTION generate_digital_id()
RETURNS TRIGGER AS $$
DECLARE
  v_state_code    text;
  v_district_code text;
  v_year          integer;
  v_seq           bigint;
BEGIN
  -- Look up codes
  SELECT code INTO v_state_code
    FROM state_codes WHERE state_name = NEW.state;

  SELECT code INTO v_district_code
    FROM district_codes WHERE district_name = NEW.district;

  IF v_state_code IS NULL OR v_district_code IS NULL THEN
    RAISE EXCEPTION 'Unknown state "%" or district "%"', NEW.state, NEW.district;
  END IF;

  v_year := EXTRACT(YEAR FROM now());

  -- Atomically get next sequence value
  INSERT INTO digital_id_sequences (district_code, year, last_value)
    VALUES (v_district_code, v_year, 1)
    ON CONFLICT (district_code, year)
    DO UPDATE SET last_value = digital_id_sequences.last_value + 1
    RETURNING last_value INTO v_seq;

  NEW.digital_id := 'LM-IN-' || v_state_code || '-' || v_district_code
                     || '-' || v_year::text
                     || '-' || lpad(v_seq::text, 8, '0');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER trg_instruments_digital_id
  BEFORE INSERT ON instruments
  FOR EACH ROW
  WHEN (NEW.digital_id IS NULL)
  EXECUTE FUNCTION generate_digital_id();

-- Auto-update updated_at on instruments
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_instruments_updated_at
  BEFORE UPDATE ON instruments
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at();

