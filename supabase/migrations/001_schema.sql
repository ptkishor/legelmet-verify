-- ────────────────────────────────────────────────
-- 13. AUDIT LOG TABLE
-- ────────────────────────────────────────────────
-- Written ONLY by database triggers — never by application code.
-- This is the "complete digital audit trail" our presentation claims.

CREATE TABLE audit_log (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  entity_type text        NOT NULL,  -- e.g. 'instrument', 'application'
  entity_id   uuid        NOT NULL,
  action      text        NOT NULL,  -- 'INSERT', 'UPDATE', 'DELETE'
  actor_id    uuid,                  -- auth.uid() at the time
  before      jsonb,                 -- old row as JSON (NULL on INSERT)
  after       jsonb,                 -- new row as JSON (NULL on DELETE)
  ip_address  text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_actor  ON audit_log (actor_id);
CREATE INDEX idx_audit_time   ON audit_log (created_at DESC);

-- ────────────────────────────────────────────────
