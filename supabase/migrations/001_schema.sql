-- Application number generator
-- Format: APP-{state_code}-{district_code}-{year}-{seq 6 digits}
CREATE OR REPLACE FUNCTION generate_application_no()
RETURNS TRIGGER AS $$
DECLARE
  v_district      text;
  v_state         text;
  v_state_code    text;
  v_district_code text;
  v_year          integer;
  v_seq           bigint;
BEGIN
  -- Get district/state from the linked instrument
  SELECT district, state INTO v_district, v_state
    FROM instruments WHERE id = NEW.instrument_id;

  SELECT code INTO v_state_code
    FROM state_codes WHERE state_name = v_state;
  SELECT code INTO v_district_code
    FROM district_codes WHERE district_name = v_district;

  v_year := EXTRACT(YEAR FROM now());

  INSERT INTO application_no_sequences (district_code, year, last_value)
    VALUES (v_district_code, v_year, 1)
    ON CONFLICT (district_code, year)
    DO UPDATE SET last_value = application_no_sequences.last_value + 1
    RETURNING last_value INTO v_seq;

  NEW.application_no := 'APP-' || v_state_code || '-' || v_district_code
                         || '-' || v_year::text
                         || '-' || lpad(v_seq::text, 6, '0');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER trg_applications_no
  BEFORE INSERT ON applications
  FOR EACH ROW
  WHEN (NEW.application_no IS NULL)
  EXECUTE FUNCTION generate_application_no();

CREATE TRIGGER trg_applications_updated_at
