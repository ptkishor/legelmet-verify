-- Complaint number generator
-- Format: CMP-{year}-{seq 6 digits}
CREATE OR REPLACE FUNCTION generate_complaint_no()
RETURNS TRIGGER AS $$
DECLARE
  v_year integer;
  v_seq  bigint;
BEGIN
  v_year := EXTRACT(YEAR FROM now());

  INSERT INTO complaint_no_sequences (year, last_value)
    VALUES (v_year, 1)
    ON CONFLICT (year)
    DO UPDATE SET last_value = complaint_no_sequences.last_value + 1
    RETURNING last_value INTO v_seq;

  NEW.complaint_no := 'CMP-' || v_year::text || '-' || lpad(v_seq::text, 6, '0');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

